// ------------------------------------------------------------------ t() / applyLanguage
// Mode-aware lookup. In Simple mode a key may have a plain-language sibling named
// 'key@simple'; it is used when present, so the same markup/JS can show jargon-free wording
// to everyday users and the precise wording in Advanced mode. Lookup order:
//   current language (@simple, then normal) -> English (@simple, then normal) -> the key itself.
// `uiMode` lives in ui.js (a classic script sharing this global scope); it is only read at
// call time, never at load time.
function t(key, params) {
  const dict = I18N[currentLang] || I18N.en;
  const simple = (typeof uiMode !== 'undefined' && uiMode === 'simple');
  let str;
  if (simple && dict[key + '@simple'] !== undefined) str = dict[key + '@simple'];
  else if (dict[key] !== undefined) str = dict[key];
  else if (simple && I18N.en[key + '@simple'] !== undefined) str = I18N.en[key + '@simple'];
  else if (I18N.en[key] !== undefined) str = I18N.en[key];
  else str = key;
  if (params) {
    Object.keys(params).forEach(function (k) {
      str = str.split('{' + k + '}').join(params[k] === null || params[k] === undefined ? '' : params[k]);
    });
  }
  return str;
}

function applyLanguage(lang) {
  currentLang = (lang === 'fa') ? 'fa' : 'en';
  try { localStorage.setItem('anigma_lang', currentLang); } catch (e) {}

  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === 'fa' ? 'rtl' : 'ltr';
  document.title = t('doc.title');

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const key = el.getAttribute('data-i18n');
    const hasElementChildren = Array.from(el.childNodes).some(function (n) { return n.nodeType === 1; });
    if (hasElementChildren) {
      // Only replace text nodes, preserving nested elements (e.g. icons inside buttons).
      Array.from(el.childNodes).forEach(function (n) {
        if (n.nodeType === 3) n.textContent = '';
      });
      if (el.childNodes.length) el.insertBefore(document.createTextNode(t(key)), el.firstChild);
      else el.textContent = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
  document.querySelectorAll('[data-i18n-title]').forEach(function (el) { el.title = t(el.getAttribute('data-i18n-title')); });
  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });

  if (typeof renderHelp === 'function') renderHelp();
  if (typeof renderDynamicText === 'function') renderDynamicText();
  if (typeof idRenderContacts === 'function') idRenderContacts();
  if (typeof idRenderContactSelect === 'function') idRenderContactSelect();
  if (typeof secSyncAnonUI === 'function') secSyncAnonUI();
  if (typeof renderStatus === 'function') renderStatus();
  if (typeof renderLogs === 'function') renderLogs();

  // Any banner built once via t()+innerHTML (rather than [data-i18n]) is not touched by
  // the loop above, so after a language switch it would keep showing the old language.
  // Re-displaying a previous decryption result isn't worth the complexity of re-rendering
  // it in place, so we just clear it — the safest way to avoid mixed-language text.
  if (typeof secClearBanner === 'function') {
    const sb = document.getElementById('secBanner');
    if (sb && sb.style.display !== 'none') secClearBanner();
  }
}
